ok(ids(L.filter(x => F.match(x, {}))) === "abcd", "空条件全部显示");
ok(ids(L.filter(x => F.match(x, { beds: "2" }))) === "bd" && ids(L.filter(x => F.match(x, { beds: "3" }))) === "c", "卧室数：2 房、3 房+");
ok(ids(L.filter(x => F.match(x, { feat: ["furn"] }))) === "ac", "带家具：字段 true 或介绍写'家具齐全'；false 不算");
